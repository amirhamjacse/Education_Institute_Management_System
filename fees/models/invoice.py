from decimal import Decimal

from django.conf import settings
from django.db import models
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from students.models.commonfields import CommonFields
from students.models.students_info import StudentsInfo
from students.models.class_studn import ClassName, SectionClas
from .fee_head import FeeHead
from .fee_structure import FeeStructure

INVOICE_STATUS = (
    ('unpaid', 'Unpaid'),
    ('partial', 'Partially Paid'),
    ('paid', 'Paid'),
    ('overdue', 'Overdue'),
    ('cancelled', 'Cancelled'),
)


class Invoice(CommonFields):
    invoice_no = models.CharField(
        _("Invoice No"), max_length=30, unique=True,
        editable=False, blank=True
    )
    student = models.ForeignKey(
        StudentsInfo, on_delete=models.CASCADE,
        verbose_name="Student", related_name='invoices'
    )
    class_name = models.ForeignKey(
        ClassName, on_delete=models.SET_NULL, null=True,
        verbose_name="Class", related_name='invoices'
    )
    section = models.ForeignKey(
        SectionClas, on_delete=models.SET_NULL, null=True, blank=True,
        verbose_name="Section", related_name='invoices'
    )
    fee_structure = models.ForeignKey(
        FeeStructure, on_delete=models.SET_NULL, null=True, blank=True,
        verbose_name="Fee Structure", related_name='invoices'
    )
    fee_head = models.ForeignKey(
        FeeHead, on_delete=models.PROTECT,
        verbose_name="Fee Head", related_name='invoices'
    )
    session = models.CharField(_("Session"), max_length=20)
    period_label = models.CharField(
        _("Period"), max_length=30, blank=True, null=True
    )
    amount = models.DecimalField(_("Amount"), max_digits=10, decimal_places=2)
    discount = models.DecimalField(
        _("Discount"), max_digits=10, decimal_places=2, default=0
    )
    due_date = models.DateField(_("Due Date"))
    status = models.CharField(
        _("Status"), max_length=10, choices=INVOICE_STATUS, default='unpaid'
    )
    remarks = models.CharField(
        _("Remarks"), max_length=255, blank=True, null=True
    )
    generated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, blank=True, verbose_name="Generated By",
        related_name='invoices_generated'
    )

    class Meta:
        ordering = ['-created_time']
        indexes = [
            models.Index(fields=['student', 'status']),
            models.Index(fields=['due_date']),
        ]

    def __str__(self):
        return f"{self.invoice_no} - {self.student}"

    def save(self, *args, **kwargs):
        is_new = self.pk is None
        super().save(*args, **kwargs)
        if is_new and not self.invoice_no:
            # invoice_no needs the auto PK, so it's generated in a second
            # save right after the initial insert.
            self.invoice_no = f"INV-{self.pk:06d}"
            super().save(update_fields=['invoice_no'])

    @property
    def net_amount(self):
        return self.amount - self.discount

    @property
    def paid_amount(self):
        total = self.payments.exclude(is_deleted=True).aggregate(
            total=models.Sum('amount')
        )['total']
        return total or Decimal('0')

    @property
    def due_amount(self):
        return self.net_amount - self.paid_amount

    def recompute_status(self, save=True):
        """Recompute status from paid_amount vs net_amount.

        Call inside the same transaction as any Payment create/void, with
        the Invoice row locked (select_for_update), so concurrent payment
        postings against the same invoice can't lose an update.
        """
        if self.status == 'cancelled':
            return
        paid = self.paid_amount
        if paid <= 0:
            new_status = (
                'overdue' if self.due_date < timezone.now().date()
                else 'unpaid'
            )
        elif paid < self.net_amount:
            new_status = 'partial'
        else:
            new_status = 'paid'
        if new_status != self.status:
            self.status = new_status
            if save:
                self.save(update_fields=['status', 'last_updated'])
